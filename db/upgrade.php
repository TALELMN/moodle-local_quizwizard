/**
 * Upgrade function.
 *
 * @param int $oldversion Old plugin version.
 * @return bool
 */
function xmldb_local_quizwizard_upgrade($oldversion) {
    global $DB;

    $dbman = $DB->get_manager();

    if ($oldversion < 2026092800) {
        // Initial version, tables are created by install.xml.
        upgrade_plugin_savepoint(true, 2026092800, 'local', 'quizwizard');
    }

    return true;
}
